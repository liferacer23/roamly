export type Place = {
  id: string;
  name: string;
  city: string;
  category: string;
  latitude: number;
  longitude: number;
  duration: number;
  description: string;
  source: 'CURATED' | 'MAPTILER';
};
export function curated(query: string, city?: string): Place[] {
  return places
    .filter(
      (p) =>
        (!city || p.city === city) &&
        (p.name + ' ' + p.city + ' ' + p.category).toLowerCase().includes(query.toLowerCase()),
    )
    .map((p) => ({ ...p, source: 'CURATED' }));
}
